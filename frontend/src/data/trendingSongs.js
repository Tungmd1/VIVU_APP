/**
 * Tìm kiếm bài hát trực tuyến qua Apple Music / iTunes Search API
 * Trả về danh sách bài hát có âm thanh hát thật 100% kèm ảnh bìa album chính thức
 */
export async function searchOnlineSongs(query) {
  if (!query || !query.trim()) return [];
  try {
    const res = await fetch(`https://itunes.apple.com/search?term=${encodeURIComponent(query.trim())}&media=music&entity=song&limit=25`);
    if (!res.ok) return [];
    const data = await res.json();
    if (!data.results) return [];
    return data.results
      .filter(item => Boolean(item.previewUrl))
      .map(item => ({
        id: `itunes-${item.trackId}`,
        title: item.trackName || 'Bài hát',
        artist: item.artistName || 'Nghệ sĩ',
        genre: item.primaryGenreName || 'Pop',
        duration: '0:30',
        cover: item.artworkUrl100 ? item.artworkUrl100.replace('100x100bb', '300x300bb') : 'https://images.unsplash.com/photo-1514525253161-7a46d19cd819?w=200',
        audioUrl: item.previewUrl
      }));
  } catch (err) {
    console.warn('[Music Search] Error querying iTunes API:', err);
    return [];
  }
}

// Singleton Audio Player Engine (Phát nhạc hát thật & lặp lại mượt mà)
class WebAudioStoryPlayer {
  constructor() {
    this.audioElement = null;
    this.currentPlayingSongId = null;
    this.onStateChange = null;
  }

  playSong(song, { loop = true } = {}) {
    if (!song) return;
    this.stop();

    const songId = song.id || (typeof song === 'string' ? song : 'custom-audio');
    const audioUrl = song.audioUrl || song.url || song.audio_url || (typeof song === 'string' && song.startsWith('http') ? song : null);

    this.currentPlayingSongId = songId;

    if (audioUrl) {
      try {
        this.audioElement = new Audio(audioUrl);
        this.audioElement.volume = 0.75;
        this.audioElement.loop = Boolean(loop);
        this.audioElement.play().catch(e => console.warn('[Audio Player] Play error:', e));
        this.audioElement.onended = () => {
          if (!loop) {
            this.stop();
            if (this.onStateChange) this.onStateChange(null);
          }
        };
        if (this.onStateChange) this.onStateChange(songId);
        return;
      } catch (e) {
        console.warn('[Audio Player] HTML5 Audio failed:', e);
      }
    }
  }

  stop() {
    if (this.audioElement) {
      try {
        this.audioElement.pause();
        this.audioElement.currentTime = 0;
      } catch {}
      this.audioElement = null;
    }
    this.currentPlayingSongId = null;
    if (this.onStateChange) this.onStateChange(null);
  }

  togglePlay(song, options) {
    const songId = song.id || (typeof song === 'string' ? song : 'custom-audio');
    if (this.currentPlayingSongId === songId) {
      this.stop();
      return false;
    } else {
      this.playSong(song, options);
      return true;
    }
  }

  isPlaying(songId) {
    return this.currentPlayingSongId === songId;
  }
}

